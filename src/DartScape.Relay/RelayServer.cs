using System;
using System.Collections.Generic;
using System.IO;
using System.Net;
using System.Net.Sockets;
using System.Threading;
using DartScape.Core.Diagnostics;
using DartScape.Core.Protocol;

namespace DartScape.Relay
{
    /// <summary>
    /// A byte-level TCP relay that makes a game server reachable through NAT hairpin.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <b>The problem.</b> Two machines behind the same router cannot reach each other by
    /// the router's public address: the router will not loop the connection back inside.
    /// Port forwarding is correct, the firewall is open, and the game still says "cannot
    /// connect". The same failure appears for anyone on CGNAT, where there is no public
    /// address to forward at all.
    /// </para>
    /// <para>
    /// <b>The fix.</b> Both sides connect <em>outward</em> to the relay, and the relay joins
    /// the two streams. It is deliberately not a second game server: it does not understand
    /// the protocol, it does not simulate anything, it copies bytes. The world still runs on
    /// the game server, which keeps one authoritative simulation.
    /// </para>
    /// <para>
    /// <b>Wire format.</b> A connection starts with a small fixed header and then becomes a
    /// raw byte pipe:
    /// </para>
    /// <code>
    ///   host  -> 0xDA 0x7A | version u8 | role u8 (1) | sessionId[16] | token[16]
    ///             then the relay replies 0x00 = ready, 0x01 = bad token, 0x02 = busy
    ///   guest -> 0xDA 0x7A | version u8 | role u8 (2) | sessionId[16]
    ///             then the relay replies 0x00 = ready, 0x03 = no such session
    /// </code>
    /// <para>
    /// The session id and token are generated by the game server and handed to clients
    /// through the world list. They are an invitation, not a password: anyone with the id
    /// can join, which is exactly the same trust model as a public server address.
    /// </para>
    /// </remarks>
    public sealed class RelayServer : IDisposable
    {
        private const byte Magic0 = 0xDA;
        private const byte Magic1 = 0x7A;
        private const byte Version = 1;

        private const byte RoleHost = 1;
        private const byte RoleGuest = 2;

        private const byte StatusReady = 0x00;
        private const byte StatusBadToken = 0x01;
        private const byte StatusBusy = 0x02;
        private const byte StatusNoSession = 0x03;

        /// <summary>Header sizes, kept next to the constants they describe.</summary>
        private const int HostHeaderSize = 2 + 1 + 1 + 16 + 16;
        private const int GuestHeaderSize = 2 + 1 + 1 + 16;

        private const int BufferSize = 8192;
        private const int MaxTunnelsDefault = 64;
        private static readonly TimeSpan HandshakeTimeout = TimeSpan.FromSeconds(10);
        private static readonly TimeSpan IdleTimeout = TimeSpan.FromSeconds(120);
        private static readonly TimeSpan TunnelLifetime = TimeSpan.FromHours(6);

        private sealed class Session
        {
            public byte[] Id;
            public byte[] Token;
            public TcpClient WaitingHost;
            public NetworkStream HostStream;
            public IPEndPoint HostRemote;
            public DateTime CreatedUtc;
            public int GuestCount;
        }

        private sealed class Tunnel
        {
            public TcpClient Host;
            public TcpClient Guest;
            public NetworkStream HostStream;
            public NetworkStream GuestStream;
            public int Directions = 2;
            public long BytesHostToGuest;
            public long BytesGuestToHost;
            public DateTime StartedUtc;
            public string Id;
        }

        private readonly int _port;
        private readonly int _maxTunnels;
        private readonly int _rateLimit;

        private readonly Dictionary<string, Session> _sessions =
            new Dictionary<string, Session>(StringComparer.OrdinalIgnoreCase);

        private readonly List<Tunnel> _tunnels = new List<Tunnel>();
        private readonly object _sync = new object();

        private TcpListener _listener;
        private Thread _acceptThread;
        private Thread _maintenanceThread;
        private volatile bool _running;

        public RelayServer(int port, int maxTunnels, int rateLimitBytesPerSecond)
        {
            _port = port;
            _maxTunnels = maxTunnels < 1 ? MaxTunnelsDefault : maxTunnels;
            _rateLimit = rateLimitBytesPerSecond < 0 ? 0 : rateLimitBytesPerSecond;
        }

        /// <summary>Port actually bound.</summary>
        public int Port { get; private set; }

        /// <summary>Number of sessions currently registered.</summary>
        public int SessionCount
        {
            get { lock (_sync) return _sessions.Count; }
        }

        /// <summary>Number of live tunnels.</summary>
        public int TunnelCount
        {
            get { lock (_sync) return _tunnels.Count; }
        }

        /// <summary>True while listening.</summary>
        public bool IsRunning
        {
            get { return _running; }
        }

        public void Start()
        {
            _listener = new TcpListener(IPAddress.Any, _port);
            _listener.Server.SetSocketOption(SocketOptionLevel.Socket, SocketOptionName.ReuseAddress, true);
            _listener.Start(64);

            Port = ((IPEndPoint)_listener.LocalEndpoint).Port;
            _running = true;

            _acceptThread = new Thread(AcceptLoop) { IsBackground = true, Name = "DartScape.Relay.Accept" };
            _acceptThread.Start();

            _maintenanceThread = new Thread(MaintenanceLoop) { IsBackground = true, Name = "DartScape.Relay.Maintenance" };
            _maintenanceThread.Start();

            Log.Info("Relay", "Listening on port {0} (max {1} tunnels).", Port, _maxTunnels);
        }

        /// <summary>
        /// Registers a session that a host may attach to. Called by the game server when a
        /// player starts hosting, and surfaced through the world list.
        /// </summary>
        public string CreateSession(out string token)
        {
            var id = new byte[16];
            var secret = new byte[16];

            using (var rng = System.Security.Cryptography.RandomNumberGenerator.Create())
            {
                rng.GetBytes(id);
                rng.GetBytes(secret);
            }

            string key = ToHex(id);
            token = ToHex(secret);

            lock (_sync)
            {
                // Bound the number of sessions so a stuck host cannot exhaust memory.
                if (_sessions.Count >= _maxTunnels * 4)
                {
                    ExpireStaleSessions();
                }

                _sessions[key] = new Session
                {
                    Id = id,
                    Token = secret,
                    CreatedUtc = DateTime.UtcNow
                };
            }

            Log.Info("Relay", "Session {0} created.", key);
            return key;
        }

        /// <summary>Removes a session and drops its waiting host, if any.</summary>
        public void RemoveSession(string sessionId)
        {
            if (string.IsNullOrEmpty(sessionId)) return;

            lock (_sync)
            {
                Session session;
                if (!_sessions.TryGetValue(sessionId, out session)) return;

                if (session.WaitingHost != null)
                {
                    try { session.WaitingHost.Close(); } catch (Exception) { }
                }

                _sessions.Remove(sessionId);
            }

            Log.Info("Relay", "Session {0} removed.", sessionId);
        }

        // -- accept -----------------------------------------------------------

        private void AcceptLoop()
        {
            while (_running)
            {
                TcpClient client;

                try
                {
                    client = _listener.AcceptTcpClient();
                }
                catch (SocketException)
                {
                    if (!_running) return;
                    Thread.Sleep(100);
                    continue;
                }
                catch (ObjectDisposedException)
                {
                    return;
                }

                ThreadPool.QueueUserWorkItem(state => HandleConnection((TcpClient)state), client);
            }
        }

        private void HandleConnection(TcpClient client)
        {
            try
            {
                client.NoDelay = true;
                client.ReceiveTimeout = (int)HandshakeTimeout.TotalMilliseconds;

                NetworkStream stream = client.GetStream();

                var header = new byte[HostHeaderSize];
                int read = 0;

                // The role byte arrives before we know the full header length, so read the
                // four byte prefix first and then the rest.
                while (read < 4)
                {
                    int n = stream.Read(header, read, 4 - read);
                    if (n <= 0) { Close(client); return; }
                    read += n;
                }

                if (header[0] != Magic0 || header[1] != Magic1 || header[2] != Version)
                {
                    Close(client);
                    return;
                }

                byte role = header[3];

                if (role == RoleHost)
                {
                    while (read < HostHeaderSize)
                    {
                        int n = stream.Read(header, read, HostHeaderSize - read);
                        if (n <= 0) { Close(client); return; }
                        read += n;
                    }

                    AttachHost(client, stream, header);
                }
                else if (role == RoleGuest)
                {
                    while (read < GuestHeaderSize)
                    {
                        int n = stream.Read(header, read, GuestHeaderSize - read);
                        if (n <= 0) { Close(client); return; }
                        read += n;
                    }

                    AttachGuest(client, stream, header);
                }
                else
                {
                    Close(client);
                }
            }
            catch (Exception ex)
            {
                Log.Debug("Relay", "Handshake failed: {0}", ex.Message);
                Close(client);
            }
        }

        private void AttachHost(TcpClient client, NetworkStream stream, byte[] header)
        {
            var id = new byte[16];
            var token = new byte[16];
            Buffer.BlockCopy(header, 4, id, 0, 16);
            Buffer.BlockCopy(header, 20, token, 0, 16);

            string key = ToHex(id);
            Session session;

            lock (_sync)
            {
                if (!_sessions.TryGetValue(key, out session) || !BytesEqual(session.Token, token))
                {
                    stream.WriteByte(StatusBadToken);
                    Close(client);
                    Log.Warning("Relay", "Host attach rejected for {0}: bad token.", key);
                    return;
                }

                if (session.WaitingHost != null)
                {
                    // A host reconnecting before maintenance noticed the old socket died
                    // should simply take the slot; answering "busy" would make the player
                    // wait for nothing.
                    if (!IsDisconnected(session.WaitingHost))
                    {
                        stream.WriteByte(StatusBusy);
                        Close(client);
                        Log.Info("Relay", "Host attach rejected for {0}: already attached.", key);
                        return;
                    }

                    Close(session.WaitingHost);
                }

                session.WaitingHost = client;
                session.HostStream = stream;
                session.HostRemote = client.Client.RemoteEndPoint as IPEndPoint;
            }

            // The reply has to go out before the pipe opens, or the first game bytes would
            // arrive in front of it and the client would parse them as a status byte.
            stream.WriteByte(StatusReady);
            stream.Flush();

            Log.Info("Relay", "Host attached to session {0} from {1}.", key, session.HostRemote);
        }

        private void AttachGuest(TcpClient client, NetworkStream stream, byte[] header)
        {
            var id = new byte[16];
            Buffer.BlockCopy(header, 4, id, 0, 16);
            string key = ToHex(id);

            TcpClient host;
            NetworkStream hostStream;
            string tunnelId;

            lock (_sync)
            {
                Session session;
                if (!_sessions.TryGetValue(key, out session) || session.WaitingHost == null)
                {
                    stream.WriteByte(StatusNoSession);
                    Close(client);
                    Log.Info("Relay", "Guest rejected: no waiting host for {0}.", key);
                    return;
                }

                if (_tunnels.Count >= _maxTunnels)
                {
                    stream.WriteByte(StatusBusy);
                    Close(client);
                    Log.Warning("Relay", "Guest rejected: tunnel limit reached.");
                    return;
                }

                host = session.WaitingHost;
                hostStream = session.HostStream;

                session.WaitingHost = null;
                session.HostStream = null;
                session.GuestCount++;

                tunnelId = key + "-" + session.GuestCount.ToString();
            }

            stream.WriteByte(StatusReady);
            stream.Flush();

            hostStream.WriteByte(StatusReady);
            hostStream.Flush();

            var tunnel = new Tunnel
            {
                Host = host,
                Guest = client,
                HostStream = hostStream,
                GuestStream = stream,
                StartedUtc = DateTime.UtcNow,
                Id = tunnelId
            };

            lock (_sync)
            {
                _tunnels.Add(tunnel);
            }

            Log.Info("Relay", "Tunnel {0} opened.", tunnelId);

            // Two threads, one per direction. Half-close is honoured: when one side sends
            // EOF its direction ends and the other side is told, so a peer that has
            // finished writing still receives what was in flight.
            var hostToGuest = new Thread(() => Pump(tunnel, hostStream, stream, host, client)) { IsBackground = true };
            var guestToHost = new Thread(() => Pump(tunnel, stream, hostStream, client, host)) { IsBackground = true };

            hostToGuest.Start();
            guestToHost.Start();
        }

        private void Pump(Tunnel tunnel, NetworkStream from, NetworkStream to, TcpClient fromClient, TcpClient toClient)
        {
            var buffer = new byte[BufferSize];
            long rateWindow = 0;
            long rateBytes = 0;

            try
            {
                while (_running && (DateTime.UtcNow - tunnel.StartedUtc) < TunnelLifetime)
                {
                    int read = from.Read(buffer, 0, buffer.Length);
                    if (read <= 0) break;

                    to.Write(buffer, 0, read);
                    to.Flush();

                    if (ReferenceEquals(from, tunnel.HostStream)) tunnel.BytesHostToGuest += read;
                    else tunnel.BytesGuestToHost += read;

                    // Coarse shaping, not policing: sleeping in the pump stops reading,
                    // which is the backpressure that makes the sender slow down. No packet
                    // is dropped and the protocol is untouched.
                    if (_rateLimit > 0)
                    {
                        long now = Environment.TickCount;
                        if (now - rateWindow > 1000)
                        {
                            rateWindow = now;
                            rateBytes = 0;
                        }

                        rateBytes += read;
                        if (rateBytes > _rateLimit)
                        {
                            Thread.Sleep(20);
                        }
                    }
                }
            }
            catch (IOException)
            {
                // Peer went away.
            }
            catch (ObjectDisposedException)
            {
                // Tunnel closed underneath us.
            }
            catch (Exception ex)
            {
                Log.Debug("Relay", "Pump error in {0}: {1}", tunnel.Id, ex.Message);
            }
            finally
            {
                // Tell the other side no more data is coming, but do not close its socket:
                // the opposite direction may still be draining.
                try { toClient.Client.Shutdown(SocketShutdown.Send); } catch (Exception) { }

                if (Interlocked.Decrement(ref tunnel.Directions) == 0) CloseTunnel(tunnel);
            }
        }

        private void CloseTunnel(Tunnel tunnel)
        {
            lock (_sync)
            {
                _tunnels.Remove(tunnel);
            }

            try { tunnel.Host.Close(); } catch (Exception) { }
            try { tunnel.Guest.Close(); } catch (Exception) { }

            Log.Info("Relay", "Tunnel {0} closed ({1} up, {2} down bytes).",
                tunnel.Id, tunnel.BytesHostToGuest, tunnel.BytesGuestToHost);
        }

        // -- maintenance ------------------------------------------------------

        private void MaintenanceLoop()
        {
            while (_running)
            {
                Thread.Sleep(1000);

                try
                {
                    lock (_sync)
                    {
                        ExpireStaleSessions();
                    }
                }
                catch (Exception ex)
                {
                    Log.Debug("Relay", "Maintenance error: {0}", ex.Message);
                }
            }
        }

        private void ExpireStaleSessions()
        {
            var expired = new List<string>();

            foreach (KeyValuePair<string, Session> pair in _sessions)
            {
                Session session = pair.Value;

                if (session.WaitingHost != null && IsDisconnected(session.WaitingHost))
                {
                    Close(session.WaitingHost);
                    session.WaitingHost = null;
                    session.HostStream = null;
                }

                // Sessions with nobody attached age out so the table cannot grow forever.
                if (session.WaitingHost == null && (DateTime.UtcNow - session.CreatedUtc) > TimeSpan.FromHours(12))
                {
                    expired.Add(pair.Key);
                }
            }

            foreach (string key in expired)
            {
                _sessions.Remove(key);
                Log.Debug("Relay", "Session {0} expired.", key);
            }
        }

        /// <summary>
        /// True when a socket has been closed by its peer.
        /// </summary>
        /// <remarks>
        /// A waiting host is silent by design, so any readable state means the connection
        /// is gone: a live peer with nothing to say reports no data available.
        /// </remarks>
        private static bool IsDisconnected(TcpClient client)
        {
            if (client == null || client.Client == null) return true;

            try
            {
                return client.Client.Poll(0, SelectMode.SelectRead) && client.Client.Available == 0;
            }
            catch (Exception)
            {
                return true;
            }
        }

        private static void Close(TcpClient client)
        {
            try { client.Close(); } catch (Exception) { }
        }

        private static bool BytesEqual(byte[] a, byte[] b)
        {
            if (a == null || b == null || a.Length != b.Length) return false;

            int difference = 0;
            for (int i = 0; i < a.Length; i++) difference |= a[i] ^ b[i];
            return difference == 0;
        }

        /// <summary>Lowercase hex, which is what humans retype and what the world list shows.</summary>
        public static string ToHex(byte[] bytes)
        {
            var sb = new System.Text.StringBuilder(bytes.Length * 2);
            foreach (byte b in bytes) sb.Append(b.ToString("x2"));
            return sb.ToString();
        }

        public void Stop()
        {
            _running = false;

            try { if (_listener != null) _listener.Stop(); } catch (Exception) { }

            lock (_sync)
            {
                foreach (Tunnel tunnel in _tunnels)
                {
                    try { tunnel.Host.Close(); } catch (Exception) { }
                    try { tunnel.Guest.Close(); } catch (Exception) { }
                }
                _tunnels.Clear();

                foreach (KeyValuePair<string, Session> pair in _sessions)
                {
                    if (pair.Value.WaitingHost != null)
                    {
                        try { pair.Value.WaitingHost.Close(); } catch (Exception) { }
                    }
                }
                _sessions.Clear();
            }

            Thread accept = _acceptThread;
            if (accept != null) accept.Join(TimeSpan.FromSeconds(2));

            Thread maintenance = _maintenanceThread;
            if (maintenance != null) maintenance.Join(TimeSpan.FromSeconds(2));
        }

        public void Dispose()
        {
            Stop();

            try { if (_listener != null) _listener.Server.Close(); } catch (Exception) { }
            _listener = null;
        }
    }
}
